CREATE TABLE IF NOT EXISTS public."user" (
  id SERIAL PRIMARY KEY, email VARCHAR(254) NOT NULL, username VARCHAR(40) NOT NULL,
  password TEXT NOT NULL, nom VARCHAR(80) NOT NULL DEFAULT '', prenom VARCHAR(80) NOT NULL DEFAULT '',
  avatar_url TEXT, auth_version INTEGER NOT NULL DEFAULT 0
);
ALTER TABLE public."user" ADD COLUMN IF NOT EXISTS auth_version INTEGER NOT NULL DEFAULT 0;
ALTER TABLE public."user" ADD COLUMN IF NOT EXISTS avatar_url TEXT;
CREATE UNIQUE INDEX IF NOT EXISTS nspy_user_email_unique ON public."user" (lower(email));
CREATE TABLE IF NOT EXISTS scans (
  id SERIAL PRIMARY KEY, user_id INTEGER NOT NULL REFERENCES public."user"(id) ON DELETE CASCADE,
  tool_type VARCHAR(16) NOT NULL, target TEXT, result_count INTEGER,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), status VARCHAR(16) NOT NULL DEFAULT 'success',
  severity VARCHAR(16) NOT NULL DEFAULT 'info', duration_ms INTEGER NOT NULL DEFAULT 0,
  detail JSONB NOT NULL DEFAULT '{}', document_status VARCHAR(16) NOT NULL DEFAULT 'sql'
);
ALTER TABLE scans ADD COLUMN IF NOT EXISTS status VARCHAR(16) NOT NULL DEFAULT 'success';
ALTER TABLE scans ADD COLUMN IF NOT EXISTS severity VARCHAR(16) NOT NULL DEFAULT 'info';
ALTER TABLE scans ADD COLUMN IF NOT EXISTS duration_ms INTEGER NOT NULL DEFAULT 0;
ALTER TABLE scans ADD COLUMN IF NOT EXISTS detail JSONB NOT NULL DEFAULT '{}';
ALTER TABLE scans ADD COLUMN IF NOT EXISTS document_status VARCHAR(16) NOT NULL DEFAULT 'sql';
CREATE INDEX IF NOT EXISTS nspy_scans_owner_date ON scans(user_id, created_at);
CREATE TABLE IF NOT EXISTS user_files (
  id UUID PRIMARY KEY, user_id INTEGER NOT NULL REFERENCES public."user"(id) ON DELETE CASCADE,
  stored_name TEXT NOT NULL UNIQUE, original_name VARCHAR(255) NOT NULL, mime_type VARCHAR(32) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS nspy_files_owner ON user_files(user_id);
